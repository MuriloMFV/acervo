"""Prepare the supplied vector logos for SvgXml; keep the originals unchanged.

Run: python3 src/assets/distribuidoras/generate-native.py
Disney's embedded PNG is extracted byte for byte, without raster conversion.
"""
from pathlib import Path
import base64
import json
import re
import xml.etree.ElementTree as ET

folder = Path(__file__).parent
SVG = 'http://www.w3.org/2000/svg'
ET.register_namespace('', SVG)
sources = {
    'fox': '20th_Century_Fox_Home_Entertainment.svg',
    'bbc': 'bbc_logo_icon_181255.svg',
    'miramax': 'cdnlogo.com_miramax-films-logo.svg',
    'marvel': 'Marvel_Studios_2016_logo.svg',
    'universal': 'Universal_Pictures_logo.svg',
    'warner': 'Warner_Home_Video.svg',
    'sony': 'Sony_Pictures_Home_Entertainment_Print_Logo.svg',
}
logos = {}
for name, file in sources.items():
    root = ET.parse(folder / file).getroot()
    # These logos do not reference their defs; metadata and unused definitions
    # contain editor-specific elements that the native SVG renderer cannot use.
    assert not any('url(' in value or 'href' in key for node in root.iter() for key, value in node.attrib.items())
    for parent in root.iter():
        for child in list(parent):
            if child.tag.split('}')[-1] in ['metadata', 'namedview', 'defs', 'pattern', 'title', 'style']:
                parent.remove(child)
    for node in root.iter():
        if node.get('class') == 'st0':
            node.set('fill', '#231F20')
        for attr in list(node.attrib):
            if attr.startswith('{') or attr in ['id', 'class', 'version', 'enable-background']:
                del node.attrib[attr]
    root.attrib.pop('width', None)
    root.attrib.pop('height', None)
    if name == 'bbc':
        root.set('viewBox', '5 15.72 30 8.56')
    elif name == 'miramax':
        root.set('viewBox', '67.5 208.4 365 83')
    # Keep path data, transforms, fills and the artwork's aspect ratio.
    logos[name] = re.sub(r'>\s+<', '><', ET.tostring(root, encoding='unicode'))

out = '// Generated by generate-native.py from the supplied SVGs. Do not edit by hand.\n'
out += 'export const distributorSvgLogos = ' + json.dumps(logos, ensure_ascii=False, indent=2) + ' as const;\n'
(folder / 'native.ts').write_text(out)
disney = ET.parse(folder / 'walt-disney-home-entertainment-logo-png_seeklogo-151334.svg').getroot()
embedded = next(node for node in disney.iter() if node.tag.split('}')[-1] == 'image').get('href')
assert embedded.startswith('data:image/png;base64,')
(folder / 'disney-native.png').write_bytes(base64.b64decode(embedded.split(',', 1)[1]))
